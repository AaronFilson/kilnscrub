//go:build ignore

// Command branch_coverage analyzes a Go coverage profile (produced by
// `go test -race -covermode=atomic -coverprofile=coverage.out ./...`) and
// computes exact Statement, Executable Line, and AST Control-Flow Branch
// coverage per package and across the repository using only the Go standard
// library (`go/parser`, `go/ast`, `go/token`, `go/scanner`).
//
// Usage:
//
//	go run ./scripts/branch_coverage.go -profile coverage.out [-markdown docs/TEST_COVERAGE.md]
//	go run ./scripts/branch_coverage.go -profile coverage.out -min-line 80 -min-branch 70
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/scanner"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// coverBlock represents one basic block entry from a Go coverage profile.
type coverBlock struct {
	File      string
	StartLine int
	StartCol  int
	EndLine   int
	EndCol    int
	NumStmt   int
	Count     int64

	// Byte offsets within the source file (populated after reading source).
	StartOff int
	EndOff   int
}

type posKey struct {
	line int
	col  int
}

// BranchRecord represents a single AST control-flow branch and its hit count.
type BranchRecord struct {
	Package  string `json:"package"`
	File     string `json:"file"`
	Line     int    `json:"line"`
	FuncName string `json:"func_name"`
	Kind     string `json:"kind"`
	Detail   string `json:"detail"`
	Hits     int64  `json:"hits"`
	Covered  bool   `json:"covered"`
}

// FileMetrics holds Statement, Line, and Branch metrics for a single Go file.
type FileMetrics struct {
	Package         string         `json:"package"`
	File            string         `json:"file"`
	StmtsCovered    int            `json:"stmts_covered"`
	StmtsTotal      int            `json:"stmts_total"`
	LinesCovered    int            `json:"lines_covered"`
	LinesTotal      int            `json:"lines_total"`
	BranchesCovered int            `json:"branches_covered"`
	BranchesTotal   int            `json:"branches_total"`
	Uncovered       []BranchRecord `json:"uncovered_branches,omitempty"`
}

// PackageMetrics aggregates metrics across all profiled files in a package.
type PackageMetrics struct {
	Package         string         `json:"package"`
	Files           []FileMetrics  `json:"files"`
	StmtsCovered    int            `json:"stmts_covered"`
	StmtsTotal      int            `json:"stmts_total"`
	StmtPct         float64        `json:"stmt_pct"`
	LinesCovered    int            `json:"lines_covered"`
	LinesTotal      int            `json:"lines_total"`
	LinePct         float64        `json:"line_pct"`
	BranchesCovered int            `json:"branches_covered"`
	BranchesTotal   int            `json:"branches_total"`
	BranchPct       float64        `json:"branch_pct"`
	Uncovered       []BranchRecord `json:"uncovered_branches,omitempty"`
}

// RepoReport holds the complete coverage analysis result.
type RepoReport struct {
	Module          string            `json:"module"`
	Mode            string            `json:"mode"`
	ProfilePath     string            `json:"profile_path"`
	Packages        []PackageMetrics  `json:"packages"`
	StmtsCovered    int               `json:"stmts_covered"`
	StmtsTotal      int               `json:"stmts_total"`
	StmtPct         float64           `json:"stmt_pct"`
	LinesCovered    int               `json:"lines_covered"`
	LinesTotal      int               `json:"lines_total"`
	LinePct         float64           `json:"line_pct"`
	BranchesCovered int               `json:"branches_covered"`
	BranchesTotal   int               `json:"branches_total"`
	BranchPct       float64           `json:"branch_pct"`
	BranchKinds     map[string][2]int `json:"branch_kinds"` // kind -> [covered, total]
	Warnings        []string          `json:"warnings,omitempty"`
}

func pct(covered, total int) float64 {
	if total == 0 {
		return 100.0
	}
	return 100.0 * float64(covered) / float64(total)
}

func main() {
	profilePath := flag.String("profile", "coverage.out", "Path to Go coverage profile generated by go test -coverprofile")
	rootDir := flag.String("root", ".", "Path to Go module root containing go.mod")
	markdownPath := flag.String("markdown", "", "Optional output path for Markdown coverage report (e.g. docs/TEST_COVERAGE.md)")
	topPerPkg := flag.Int("top", 5, "Number of top uncovered branches per package to display in terminal output")
	minStmt := flag.Float64("min-stmt", 0, "Fail with exit code 1 if total statement coverage % is below this threshold")
	minLine := flag.Float64("min-line", 0, "Fail with exit code 1 if total executable line coverage % is below this threshold")
	minBranch := flag.Float64("min-branch", 0, "Fail with exit code 1 if total AST branch coverage % is below this threshold")
	jsonOut := flag.Bool("json", false, "Print full report as JSON to stdout")
	flag.Parse()

	report, err := analyze(*rootDir, *profilePath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "branch_coverage: %v\n", err)
		os.Exit(2)
	}

	if *markdownPath != "" {
		if err := writeMarkdownReport(*markdownPath, report); err != nil {
			fmt.Fprintf(os.Stderr, "branch_coverage: failed to write markdown report: %v\n", err)
			os.Exit(2)
		}
	}

	if *jsonOut {
		enc := json.NewEncoder(os.Stdout)
		enc.SetIndent("", "  ")
		if err := enc.Encode(report); err != nil {
			fmt.Fprintf(os.Stderr, "branch_coverage: failed to encode JSON: %v\n", err)
			os.Exit(2)
		}
	} else {
		printTextReport(os.Stdout, report, *topPerPkg)
	}

	var failures []string
	if *minStmt > 0 && report.StmtPct < *minStmt {
		failures = append(failures, fmt.Sprintf("statement coverage %.1f%% < required %.1f%%", report.StmtPct, *minStmt))
	}
	if *minLine > 0 && report.LinePct < *minLine {
		failures = append(failures, fmt.Sprintf("line coverage %.1f%% < required %.1f%%", report.LinePct, *minLine))
	}
	if *minBranch > 0 && report.BranchPct < *minBranch {
		failures = append(failures, fmt.Sprintf("branch coverage %.1f%% < required %.1f%%", report.BranchPct, *minBranch))
	}
	if len(failures) > 0 {
		for _, msg := range failures {
			fmt.Fprintf(os.Stderr, "FAIL: %s\n", msg)
		}
		os.Exit(1)
	}
}

func readModulePath(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", fmt.Errorf("reading go.mod: %w", err)
	}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "module ") {
			mod := strings.TrimSpace(strings.TrimPrefix(line, "module "))
			mod = strings.Trim(mod, `"`)
			if mod != "" {
				return mod, nil
			}
		}
	}
	return "", fmt.Errorf("module directive not found in %s", filepath.Join(root, "go.mod"))
}

func parseProfile(profilePath string) (string, map[string][]coverBlock, error) {
	f, err := os.Open(profilePath)
	if err != nil {
		return "", nil, fmt.Errorf("opening profile %s: %w", profilePath, err)
	}
	defer f.Close()

	type blockKey struct {
		file      string
		startLine int
		startCol  int
		endLine   int
		endCol    int
		numStmt   int
	}

	var mode string
	merged := make(map[blockKey]int64)
	fileSet := make(map[string]struct{})

	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	lineNo := 0
	for sc.Scan() {
		lineNo++
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "mode:") {
			m := strings.TrimSpace(strings.TrimPrefix(line, "mode:"))
			if mode == "" {
				mode = m
			} else if mode != m {
				return "", nil, fmt.Errorf("conflicting coverage modes %q and %q at line %d", mode, m, lineNo)
			}
			continue
		}

		// Format: <file>:<startLine>.<startCol>,<endLine>.<endCol> <numStmt> <count>
		fields := strings.Fields(line)
		if len(fields) != 3 {
			return "", nil, fmt.Errorf("malformed coverage line %d: %q", lineNo, line)
		}
		colonIdx := strings.LastIndex(fields[0], ":")
		if colonIdx < 0 {
			return "", nil, fmt.Errorf("missing colon at line %d: %q", lineNo, line)
		}
		fileName := fields[0][:colonIdx]
		span := fields[0][colonIdx+1:]
		commaIdx := strings.Index(span, ",")
		if commaIdx < 0 {
			return "", nil, fmt.Errorf("missing comma in span at line %d: %q", lineNo, line)
		}
		startLine, startCol, err := parseLineCol(span[:commaIdx])
		if err != nil {
			return "", nil, fmt.Errorf("invalid start position at line %d: %w", lineNo, err)
		}
		endLine, endCol, err := parseLineCol(span[commaIdx+1:])
		if err != nil {
			return "", nil, fmt.Errorf("invalid end position at line %d: %w", lineNo, err)
		}
		numStmt, err := strconv.Atoi(fields[1])
		if err != nil {
			return "", nil, fmt.Errorf("invalid numStmt at line %d: %w", lineNo, err)
		}
		count, err := strconv.ParseInt(fields[2], 10, 64)
		if err != nil {
			return "", nil, fmt.Errorf("invalid count at line %d: %w", lineNo, err)
		}

		key := blockKey{
			file:      fileName,
			startLine: startLine,
			startCol:  startCol,
			endLine:   endLine,
			endCol:    endCol,
			numStmt:   numStmt,
		}
		if prev, ok := merged[key]; ok {
			if mode == "set" {
				if count > prev {
					merged[key] = count
				}
			} else {
				merged[key] = prev + count
			}
		} else {
			merged[key] = count
		}
		fileSet[fileName] = struct{}{}
	}
	if err := sc.Err(); err != nil {
		return "", nil, fmt.Errorf("reading profile: %w", err)
	}
	if mode == "" {
		return "", nil, fmt.Errorf("coverage profile %s has no mode header", profilePath)
	}

	byFile := make(map[string][]coverBlock, len(fileSet))
	for k, cnt := range merged {
		byFile[k.file] = append(byFile[k.file], coverBlock{
			File:      k.file,
			StartLine: k.startLine,
			StartCol:  k.startCol,
			EndLine:   k.endLine,
			EndCol:    k.endCol,
			NumStmt:   k.numStmt,
			Count:     cnt,
		})
	}
	for fn := range byFile {
		blocks := byFile[fn]
		sort.Slice(blocks, func(i, j int) bool {
			if blocks[i].StartLine != blocks[j].StartLine {
				return blocks[i].StartLine < blocks[j].StartLine
			}
			if blocks[i].StartCol != blocks[j].StartCol {
				return blocks[i].StartCol < blocks[j].StartCol
			}
			if blocks[i].EndLine != blocks[j].EndLine {
				return blocks[i].EndLine < blocks[j].EndLine
			}
			return blocks[i].EndCol < blocks[j].EndCol
		})
		byFile[fn] = blocks
	}
	return mode, byFile, nil
}

func parseLineCol(s string) (int, int, error) {
	dot := strings.IndexByte(s, '.')
	if dot < 0 {
		return 0, 0, fmt.Errorf("expected line.col, got %q", s)
	}
	line, err := strconv.Atoi(s[:dot])
	if err != nil {
		return 0, 0, err
	}
	col, err := strconv.Atoi(s[dot+1:])
	if err != nil {
		return 0, 0, err
	}
	return line, col, nil
}

func analyze(rootDir, profilePath string) (*RepoReport, error) {
	modPath, err := readModulePath(rootDir)
	if err != nil {
		return nil, err
	}
	mode, blocksByFile, err := parseProfile(profilePath)
	if err != nil {
		return nil, err
	}

	report := &RepoReport{
		Module:      modPath,
		Mode:        mode,
		ProfilePath: profilePath,
		BranchKinds: make(map[string][2]int),
	}
	if mode == "set" {
		report.Warnings = append(report.Warnings,
			"coverage profile uses mode: set; implicit-else and implicit-default counts are exact only with -covermode=count or -covermode=atomic")
	}

	pkgMap := make(map[string]*PackageMetrics)
	fileKeys := make([]string, 0, len(blocksByFile))
	for k := range blocksByFile {
		fileKeys = append(fileKeys, k)
	}
	sort.Strings(fileKeys)

	for _, profFile := range fileKeys {
		relPath, ok := resolveRelPath(modPath, profFile)
		if !ok {
			continue
		}
		absPath := filepath.Join(rootDir, filepath.FromSlash(relPath))
		src, err := os.ReadFile(absPath)
		if err != nil {
			return nil, fmt.Errorf("reading source file %s: %w", absPath, err)
		}

		pkgName := path.Dir(relPath)
		if pkgName == "." {
			pkgName = modPath
		}

		blocks := blocksByFile[profFile]
		lineStarts := computeLineStarts(src)
		for i := range blocks {
			blocks[i].StartOff = lineColToOffset(lineStarts, len(src), blocks[i].StartLine, blocks[i].StartCol)
			blocks[i].EndOff = lineColToOffset(lineStarts, len(src), blocks[i].EndLine, blocks[i].EndCol)
		}

		fm, branches, err := analyzeFile(pkgName, relPath, src, blocks, mode)
		if err != nil {
			return nil, fmt.Errorf("analyzing %s: %w", relPath, err)
		}

		for _, br := range branches {
			pair := report.BranchKinds[br.Kind]
			if br.Covered {
				pair[0]++
			}
			pair[1]++
			report.BranchKinds[br.Kind] = pair
		}

		pm, exists := pkgMap[pkgName]
		if !exists {
			pm = &PackageMetrics{Package: pkgName}
			pkgMap[pkgName] = pm
		}
		pm.Files = append(pm.Files, fm)
		pm.StmtsCovered += fm.StmtsCovered
		pm.StmtsTotal += fm.StmtsTotal
		pm.LinesCovered += fm.LinesCovered
		pm.LinesTotal += fm.LinesTotal
		pm.BranchesCovered += fm.BranchesCovered
		pm.BranchesTotal += fm.BranchesTotal
		pm.Uncovered = append(pm.Uncovered, fm.Uncovered...)
	}

	pkgNames := make([]string, 0, len(pkgMap))
	for k := range pkgMap {
		pkgNames = append(pkgNames, k)
	}
	sort.Strings(pkgNames)

	for _, name := range pkgNames {
		pm := pkgMap[name]
		pm.StmtPct = pct(pm.StmtsCovered, pm.StmtsTotal)
		pm.LinePct = pct(pm.LinesCovered, pm.LinesTotal)
		pm.BranchPct = pct(pm.BranchesCovered, pm.BranchesTotal)
		sort.Slice(pm.Uncovered, func(i, j int) bool {
			if pm.Uncovered[i].File != pm.Uncovered[j].File {
				return pm.Uncovered[i].File < pm.Uncovered[j].File
			}
			if pm.Uncovered[i].Line != pm.Uncovered[j].Line {
				return pm.Uncovered[i].Line < pm.Uncovered[j].Line
			}
			return pm.Uncovered[i].Kind < pm.Uncovered[j].Kind
		})
		report.Packages = append(report.Packages, *pm)
		report.StmtsCovered += pm.StmtsCovered
		report.StmtsTotal += pm.StmtsTotal
		report.LinesCovered += pm.LinesCovered
		report.LinesTotal += pm.LinesTotal
		report.BranchesCovered += pm.BranchesCovered
		report.BranchesTotal += pm.BranchesTotal
	}

	report.StmtPct = pct(report.StmtsCovered, report.StmtsTotal)
	report.LinePct = pct(report.LinesCovered, report.LinesTotal)
	report.BranchPct = pct(report.BranchesCovered, report.BranchesTotal)

	return report, nil
}

func resolveRelPath(modPath, profFile string) (string, bool) {
	profFile = filepath.ToSlash(profFile)
	prefix := modPath + "/"
	if strings.HasPrefix(profFile, prefix) {
		return strings.TrimPrefix(profFile, prefix), true
	}
	if !strings.HasPrefix(profFile, "/") && !strings.Contains(profFile, ":") {
		return profFile, true
	}
	return "", false
}

func computeLineStarts(src []byte) []int {
	starts := []int{0}
	for i, b := range src {
		if b == '\n' {
			starts = append(starts, i+1)
		}
	}
	return starts
}

func lineColToOffset(lineStarts []int, srcLen, line, col int) int {
	if line < 1 {
		return 0
	}
	if line > len(lineStarts) {
		return srcLen
	}
	off := lineStarts[line-1] + (col - 1)
	if off < 0 {
		return 0
	}
	if off > srcLen {
		return srcLen
	}
	return off
}

func analyzeFile(pkgName, relPath string, src []byte, blocks []coverBlock, mode string) (FileMetrics, []BranchRecord, error) {
	fm := FileMetrics{
		Package: pkgName,
		File:    relPath,
	}

	// 1. Exact statement coverage (matches `go tool cover -func`).
	for _, b := range blocks {
		fm.StmtsTotal += b.NumStmt
		if b.Count > 0 {
			fm.StmtsCovered += b.NumStmt
		}
	}

	fset := token.NewFileSet()
	astFile, err := parser.ParseFile(fset, relPath, src, parser.ParseComments)
	if err != nil {
		return fm, nil, fmt.Errorf("parsing AST: %w", err)
	}
	tokFile := fset.File(astFile.Pos())

	// 2. Exact executable line coverage via go/scanner token-to-block mapping.
	fm.LinesCovered, fm.LinesTotal = computeLineCoverage(tokFile, src, blocks)

	// 3. AST control-flow branch coverage.
	analyzer := newFileBranchAnalyzer(pkgName, relPath, fset, tokFile, src, blocks, mode)
	analyzer.walkFile(astFile)

	fm.BranchesTotal = len(analyzer.branches)
	for _, br := range analyzer.branches {
		if br.Covered {
			fm.BranchesCovered++
		} else {
			fm.Uncovered = append(fm.Uncovered, br)
		}
	}
	return fm, analyzer.branches, nil
}

// computeLineCoverage marks every line containing at least one executable
// non-brace token inside any NumStmt>0 coverage block, and considers a line
// covered if any block containing executable tokens on that line has Count > 0.
func computeLineCoverage(tokFile *token.File, src []byte, blocks []coverBlock) (covered, total int) {
	stmtBlocks := make([]coverBlock, 0, len(blocks))
	for _, b := range blocks {
		if b.NumStmt > 0 {
			stmtBlocks = append(stmtBlocks, b)
		}
	}
	if len(stmtBlocks) == 0 {
		return 0, 0
	}

	var s scanner.Scanner
	s.Init(tokFile, src, nil, 0) // skip comments

	lineCovered := make(map[int]bool)
	for {
		pos, tok, _ := s.Scan()
		if tok == token.EOF {
			break
		}
		if tok == token.SEMICOLON || tok == token.LBRACE || tok == token.RBRACE || tok == token.COMMENT {
			continue
		}
		off := tokFile.Offset(pos)
		line := tokFile.Line(pos)
		for _, b := range stmtBlocks {
			if off >= b.StartOff && off < b.EndOff {
				if _, exists := lineCovered[line]; !exists {
					lineCovered[line] = false
				}
				if b.Count > 0 {
					lineCovered[line] = true
				}
			}
		}
	}

	total = len(lineCovered)
	for _, cov := range lineCovered {
		if cov {
			covered++
		}
	}
	return covered, total
}

type fileBranchAnalyzer struct {
	pkgName string
	relPath string
	fset    *token.FileSet
	tokFile *token.File
	src     []byte
	blocks  []coverBlock
	mode    string

	byStart map[posKey][]coverBlock
	byEnd   map[posKey][]coverBlock

	curFunc  string
	branches []BranchRecord
}

func newFileBranchAnalyzer(pkgName, relPath string, fset *token.FileSet, tokFile *token.File, src []byte, blocks []coverBlock, mode string) *fileBranchAnalyzer {
	a := &fileBranchAnalyzer{
		pkgName: pkgName,
		relPath: relPath,
		fset:    fset,
		tokFile: tokFile,
		src:     src,
		blocks:  blocks,
		mode:    mode,
		byStart: make(map[posKey][]coverBlock, len(blocks)),
		byEnd:   make(map[posKey][]coverBlock, len(blocks)),
	}
	for _, b := range blocks {
		sk := posKey{b.StartLine, b.StartCol}
		a.byStart[sk] = append(a.byStart[sk], b)
		ek := posKey{b.EndLine, b.EndCol}
		a.byEnd[ek] = append(a.byEnd[ek], b)
	}
	return a
}

func (a *fileBranchAnalyzer) blockStartingAt(p token.Pos) (coverBlock, bool) {
	pos := a.fset.Position(p)
	if list := a.byStart[posKey{pos.Line, pos.Column}]; len(list) > 0 {
		return list[0], true
	}
	return coverBlock{}, false
}

func (a *fileBranchAnalyzer) blockEndingAt(p token.Pos) (coverBlock, bool) {
	pos := a.fset.Position(p)
	if list := a.byEnd[posKey{pos.Line, pos.Column}]; len(list) > 0 {
		// If multiple blocks end at the same pos, prefer the one with non-zero span.
		best := list[0]
		for _, b := range list[1:] {
			if (b.EndOff - b.StartOff) > (best.EndOff - best.StartOff) {
				best = b
			}
		}
		return best, true
	}
	return coverBlock{}, false
}

func (a *fileBranchAnalyzer) blockContaining(p token.Pos) (coverBlock, bool) {
	off := a.tokFile.Offset(p)
	var best coverBlock
	found := false
	bestSpan := int(^uint(0) >> 1)
	for _, b := range a.blocks {
		if off >= b.StartOff && off <= b.EndOff {
			span := b.EndOff - b.StartOff
			if !found || span < bestSpan {
				best = b
				bestSpan = span
				found = true
			}
		}
	}
	return best, found
}

func (a *fileBranchAnalyzer) entryCountFor(stmt ast.Stmt, bodyLbrace token.Pos) int64 {
	if b, ok := a.blockEndingAt(bodyLbrace); ok {
		return b.Count
	}
	if b, ok := a.blockContaining(stmt.Pos()); ok {
		return b.Count
	}
	return 0
}

func (a *fileBranchAnalyzer) emit(line int, kind, detail string, hits int64) {
	if hits < 0 {
		hits = 0
	}
	a.branches = append(a.branches, BranchRecord{
		Package:  a.pkgName,
		File:     a.relPath,
		Line:     line,
		FuncName: a.curFunc,
		Kind:     kind,
		Detail:   detail,
		Hits:     hits,
		Covered:  hits > 0,
	})
}

func (a *fileBranchAnalyzer) walkFile(f *ast.File) {
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Body == nil {
				continue
			}
			a.curFunc = formatFuncDeclName(d)
			a.walkStmtList(d.Body.List)
		case *ast.GenDecl:
			// Inspect package-level var initializers for any func literals.
			a.curFunc = "init"
			a.walkExprsForFuncLits(d)
		}
	}
}

func formatFuncDeclName(d *ast.FuncDecl) string {
	if d.Recv != nil && len(d.Recv.List) > 0 {
		recv := exprString(d.Recv.List[0].Type)
		return fmt.Sprintf("(%s).%s", recv, d.Name.Name)
	}
	return d.Name.Name
}

func (a *fileBranchAnalyzer) walkStmtList(stmts []ast.Stmt) {
	for i, stmt := range stmts {
		var nextStmt ast.Stmt
		if i+1 < len(stmts) {
			nextStmt = stmts[i+1]
		}
		a.walkStmt(stmt, nextStmt, "")
	}
}

func (a *fileBranchAnalyzer) walkStmt(stmt ast.Stmt, nextStmt ast.Stmt, label string) {
	if stmt == nil {
		return
	}
	switch s := stmt.(type) {
	case *ast.LabeledStmt:
		a.walkStmt(s.Stmt, nextStmt, s.Label.Name)

	case *ast.BlockStmt:
		a.walkStmtList(s.List)

	case *ast.IfStmt:
		a.analyzeIfStmt(s, nextStmt)

	case *ast.SwitchStmt:
		a.analyzeSwitchStmt(s)

	case *ast.TypeSwitchStmt:
		a.analyzeTypeSwitchStmt(s)

	case *ast.SelectStmt:
		a.analyzeSelectStmt(s)

	case *ast.ForStmt:
		a.analyzeForStmt(s, nextStmt, label)

	case *ast.RangeStmt:
		a.analyzeRangeStmt(s, nextStmt, label)

	default:
		// Any other statement might contain closures (*ast.FuncLit).
		a.walkExprsForFuncLits(s)
	}
}

func (a *fileBranchAnalyzer) walkExprsForFuncLits(node ast.Node) {
	if node == nil {
		return
	}
	ast.Inspect(node, func(n ast.Node) bool {
		fl, ok := n.(*ast.FuncLit)
		if !ok {
			return true
		}
		prev := a.curFunc
		line := a.fset.Position(fl.Pos()).Line
		if prev == "" {
			a.curFunc = fmt.Sprintf("func@L%d", line)
		} else {
			a.curFunc = fmt.Sprintf("%s.func@L%d", prev, line)
		}
		a.walkStmtList(fl.Body.List)
		a.curFunc = prev
		return false
	})
}

func (a *fileBranchAnalyzer) analyzeIfStmt(s *ast.IfStmt, nextStmt ast.Stmt) {
	if s.Init != nil {
		a.walkExprsForFuncLits(s.Init)
	}
	a.walkExprsForFuncLits(s.Cond)

	entryCount := a.entryCountFor(s, s.Body.Lbrace)
	thenBlock, _ := a.blockStartingAt(s.Body.Lbrace)
	thenCount := thenBlock.Count
	condStr := compactExpr(s.Cond)
	ifLine := a.fset.Position(s.Pos()).Line

	// Branch 1: then-branch
	a.emit(ifLine, "if-then", condStr, thenCount)

	// Walk inside then-body
	a.walkStmtList(s.Body.List)

	// Branch 2: explicit else / else-if OR implicit else
	if s.Else != nil {
		elseStartPos, ok := a.findElseBlockStart(s.Body.End())
		var elseCount int64
		if ok {
			if eb, found := a.blockStartingAt(elseStartPos); found {
				elseCount = eb.Count
			}
		}
		elseLine := a.fset.Position(s.Else.Pos()).Line
		switch e := s.Else.(type) {
		case *ast.IfStmt:
			a.emit(elseLine, "if-else-if", "else of ("+condStr+")", elseCount)
			a.analyzeIfStmt(e, nextStmt)
		case *ast.BlockStmt:
			a.emit(elseLine, "if-else", "else of ("+condStr+")", elseCount)
			a.walkStmtList(e.List)
		}
	} else {
		elseCount := a.implicitElseCount(entryCount, thenCount, s.Body, nextStmt)
		a.emit(ifLine, "if-implicit-else", "!("+condStr+")", elseCount)
	}
}

func (a *fileBranchAnalyzer) implicitElseCount(entryCount, thenCount int64, body *ast.BlockStmt, nextStmt ast.Stmt) int64 {
	if entryCount == 0 {
		return 0
	}
	if a.mode != "set" {
		if entryCount > thenCount {
			return entryCount - thenCount
		}
		return 0
	}
	// mode == "set": counts are 0 or 1.
	if thenCount == 0 {
		return entryCount
	}
	if alwaysTerminates(body.List) && nextStmt != nil {
		if nb, ok := a.blockContaining(nextStmt.Pos()); ok && nb.Count > 0 {
			return 1
		}
	}
	return 0
}

// findElseBlockStart locates the exact position cmd/cover uses for an else block:
// right after the 4 bytes of the "else" keyword following bodyEnd.
func (a *fileBranchAnalyzer) findElseBlockStart(bodyEnd token.Pos) (token.Pos, bool) {
	off := a.tokFile.Offset(bodyEnd)
	if off < 0 || off >= len(a.src) {
		return token.NoPos, false
	}
	// Tokenize from bodyEnd with go/scanner (skipping comments) so any word
	// "else" inside a comment between `}` and `else` is ignored.
	subFset := token.NewFileSet()
	subFile := subFset.AddFile("", -1, len(a.src)-off)
	var s scanner.Scanner
	s.Init(subFile, a.src[off:], nil, 0)
	for {
		pos, tok, _ := s.Scan()
		if tok == token.EOF {
			return token.NoPos, false
		}
		if tok == token.ELSE {
			targetOff := off + subFile.Offset(pos) + len("else")
			if targetOff > a.tokFile.Size() {
				return token.NoPos, false
			}
			return a.tokFile.Pos(targetOff), true
		}
	}
}

func (a *fileBranchAnalyzer) analyzeSwitchStmt(s *ast.SwitchStmt) {
	if s.Init != nil {
		a.walkExprsForFuncLits(s.Init)
	}
	if s.Tag != nil {
		a.walkExprsForFuncLits(s.Tag)
	}
	if s.Body == nil || len(s.Body.List) == 0 {
		return
	}

	entryCount := a.entryCountFor(s, s.Body.Lbrace)
	hasDefault := false
	var sumCases int64
	var fallthroughHits int64

	for _, item := range s.Body.List {
		cc, ok := item.(*ast.CaseClause)
		if !ok {
			continue
		}
		for _, ex := range cc.List {
			a.walkExprsForFuncLits(ex)
		}
		cb, _ := a.blockStartingAt(cc.Colon + 1)
		ccLine := a.fset.Position(cc.Pos()).Line
		if cc.List == nil {
			hasDefault = true
			a.emit(ccLine, "switch-default", "default", cb.Count)
		} else {
			a.emit(ccLine, "switch-case", "case "+compactExprList(cc.List), cb.Count)
		}
		sumCases += cb.Count
		if ftStmt := trailingFallthrough(cc.Body); ftStmt != nil {
			if fb, ok := a.blockContaining(ftStmt.Pos()); ok {
				fallthroughHits += fb.Count
			}
		}
		a.walkStmtList(cc.Body)
	}

	if !hasDefault {
		var impCount int64
		if a.mode != "set" {
			impCount = entryCount - (sumCases - fallthroughHits)
			if impCount < 0 {
				impCount = 0
			}
		} else if entryCount > 0 && sumCases == 0 {
			impCount = 1
		}
		tagStr := "switch"
		if s.Tag != nil {
			tagStr = compactExpr(s.Tag)
		}
		a.emit(a.fset.Position(s.Pos()).Line, "switch-implicit-default", "implicit default ("+tagStr+")", impCount)
	}
}

func (a *fileBranchAnalyzer) analyzeTypeSwitchStmt(s *ast.TypeSwitchStmt) {
	if s.Init != nil {
		a.walkExprsForFuncLits(s.Init)
	}
	if s.Assign != nil {
		a.walkExprsForFuncLits(s.Assign)
	}
	if s.Body == nil || len(s.Body.List) == 0 {
		return
	}

	entryCount := a.entryCountFor(s, s.Body.Lbrace)
	hasDefault := false
	var sumCases int64

	for _, item := range s.Body.List {
		cc, ok := item.(*ast.CaseClause)
		if !ok {
			continue
		}
		cb, _ := a.blockStartingAt(cc.Colon + 1)
		ccLine := a.fset.Position(cc.Pos()).Line
		if cc.List == nil {
			hasDefault = true
			a.emit(ccLine, "type-switch-default", "default", cb.Count)
		} else {
			a.emit(ccLine, "type-switch-case", "case "+compactExprList(cc.List), cb.Count)
		}
		sumCases += cb.Count
		a.walkStmtList(cc.Body)
	}

	if !hasDefault {
		var impCount int64
		if a.mode != "set" {
			impCount = entryCount - sumCases
			if impCount < 0 {
				impCount = 0
			}
		} else if entryCount > 0 && sumCases == 0 {
			impCount = 1
		}
		a.emit(a.fset.Position(s.Pos()).Line, "type-switch-implicit-default", "implicit default (type switch)", impCount)
	}
}

func (a *fileBranchAnalyzer) analyzeSelectStmt(s *ast.SelectStmt) {
	if s.Body == nil || len(s.Body.List) == 0 {
		return
	}
	for _, item := range s.Body.List {
		cc, ok := item.(*ast.CommClause)
		if !ok {
			continue
		}
		if cc.Comm != nil {
			a.walkExprsForFuncLits(cc.Comm)
		}
		cb, _ := a.blockStartingAt(cc.Colon + 1)
		ccLine := a.fset.Position(cc.Pos()).Line
		if cc.Comm == nil {
			a.emit(ccLine, "select-default", "default", cb.Count)
		} else {
			a.emit(ccLine, "select-case", "case "+compactStmt(cc.Comm), cb.Count)
		}
		a.walkStmtList(cc.Body)
	}
}

func (a *fileBranchAnalyzer) analyzeForStmt(s *ast.ForStmt, nextStmt ast.Stmt, label string) {
	if s.Init != nil {
		a.walkExprsForFuncLits(s.Init)
	}
	if s.Cond != nil {
		a.walkExprsForFuncLits(s.Cond)
	}
	if s.Post != nil {
		a.walkExprsForFuncLits(s.Post)
	}

	entryCount := a.entryCountFor(s, s.Body.Lbrace)
	bodyBlock, _ := a.blockStartingAt(s.Body.Lbrace)
	forLine := a.fset.Position(s.Pos()).Line

	condLabel := "for { ... }"
	if s.Cond != nil {
		condLabel = compactExpr(s.Cond)
	}

	// Branch 1: entering loop body
	a.emit(forLine, "for-body", condLabel, bodyBlock.Count)

	// Branch 2: normal loop condition exit/skip (only for conditional loops;
	// unconditional `for { ... }` has no header condition to evaluate false).
	if s.Cond != nil {
		exitCount := a.loopNormalExitCount(entryCount, bodyBlock.Count, s.Body, nextStmt, label)
		a.emit(forLine, "for-exit", "exit/skip ("+condLabel+")", exitCount)
	}

	a.walkStmtList(s.Body.List)
}

func (a *fileBranchAnalyzer) analyzeRangeStmt(s *ast.RangeStmt, nextStmt ast.Stmt, label string) {
	a.walkExprsForFuncLits(s.X)

	entryCount := a.entryCountFor(s, s.Body.Lbrace)
	bodyBlock, _ := a.blockStartingAt(s.Body.Lbrace)
	rangeLine := a.fset.Position(s.Pos()).Line
	xStr := "range " + compactExpr(s.X)

	// Branch 1: entering range body
	a.emit(rangeLine, "range-body", xStr, bodyBlock.Count)

	// Branch 2: range exhaustion / zero-iteration skip
	exitCount := a.loopNormalExitCount(entryCount, bodyBlock.Count, s.Body, nextStmt, label)
	a.emit(rangeLine, "range-exit", "exit/skip ("+xStr+")", exitCount)

	a.walkStmtList(s.Body.List)
}

func (a *fileBranchAnalyzer) loopNormalExitCount(entryCount, bodyCount int64, body *ast.BlockStmt, nextStmt ast.Stmt, loopLabel string) int64 {
	if entryCount == 0 {
		return 0
	}
	breakHits, abortHits := a.countLoopEarlyExits(body, loopLabel)

	// When there is a non-labeled statement immediately after the loop, its
	// execution count equals (normal exits + breaks targeting this loop).
	if nextStmt != nil {
		if _, isLabeled := nextStmt.(*ast.LabeledStmt); !isLabeled {
			if nb, ok := a.blockContaining(nextStmt.Pos()); ok {
				if a.mode != "set" {
					v := nb.Count - breakHits
					if v < 0 {
						return 0
					}
					return v
				}
				if bodyCount == 0 {
					return 1
				}
				if nb.Count > 0 && breakHits == 0 {
					return 1
				}
				return 0
			}
		}
	}

	// No following statement (loop is last statement in block): every entry that
	// did not leave via break/return/goto/panic exited normally.
	if a.mode != "set" {
		v := entryCount - breakHits - abortHits
		if v < 0 {
			return 0
		}
		return v
	}
	if bodyCount == 0 || (breakHits == 0 && abortHits == 0) {
		return 1
	}
	return 0
}

// countLoopEarlyExits sums hit counts of `break` statements targeting this loop
// (breakHits) and `return`/`goto`/`panic` statements inside the loop body
// excluding nested function literals (abortHits).
func (a *fileBranchAnalyzer) countLoopEarlyExits(body *ast.BlockStmt, loopLabel string) (breakHits, abortHits int64) {
	var walk func(n ast.Node, breakDepth int)
	walk = func(n ast.Node, breakDepth int) {
		if n == nil {
			return
		}
		switch s := n.(type) {
		case *ast.FuncLit:
			// Returns/breaks inside closures do not exit the enclosing loop.
			return
		case *ast.BlockStmt:
			for _, st := range s.List {
				walk(st, breakDepth)
			}
		case *ast.LabeledStmt:
			walk(s.Stmt, breakDepth)
		case *ast.IfStmt:
			walk(s.Body, breakDepth)
			walk(s.Else, breakDepth)
		case *ast.ForStmt:
			walk(s.Body, breakDepth+1)
		case *ast.RangeStmt:
			walk(s.Body, breakDepth+1)
		case *ast.SwitchStmt:
			if s.Body != nil {
				for _, c := range s.Body.List {
					if cc, ok := c.(*ast.CaseClause); ok {
						for _, st := range cc.Body {
							walk(st, breakDepth+1)
						}
					}
				}
			}
		case *ast.TypeSwitchStmt:
			if s.Body != nil {
				for _, c := range s.Body.List {
					if cc, ok := c.(*ast.CaseClause); ok {
						for _, st := range cc.Body {
							walk(st, breakDepth+1)
						}
					}
				}
			}
		case *ast.SelectStmt:
			if s.Body != nil {
				for _, c := range s.Body.List {
					if cc, ok := c.(*ast.CommClause); ok {
						for _, st := range cc.Body {
							walk(st, breakDepth+1)
						}
					}
				}
			}
		case *ast.BranchStmt:
			if s.Tok == token.BREAK {
				targetsLoop := (s.Label == nil && breakDepth == 0) ||
					(s.Label != nil && loopLabel != "" && s.Label.Name == loopLabel)
				if targetsLoop {
					if b, ok := a.blockContaining(s.Pos()); ok {
						breakHits += b.Count
					}
				}
			} else if s.Tok == token.GOTO {
				if b, ok := a.blockContaining(s.Pos()); ok {
					abortHits += b.Count
				}
			}
		case *ast.ReturnStmt:
			if b, ok := a.blockContaining(s.Pos()); ok {
				abortHits += b.Count
			}
		case *ast.ExprStmt:
			if isPanicCall(s) {
				if b, ok := a.blockContaining(s.Pos()); ok {
					abortHits += b.Count
				}
			}
		}
	}
	walk(body, 0)
	return breakHits, abortHits
}

func isPanicCall(s *ast.ExprStmt) bool {
	call, ok := s.X.(*ast.CallExpr)
	if !ok {
		return false
	}
	ident, ok := call.Fun.(*ast.Ident)
	return ok && ident.Name == "panic"
}

func alwaysTerminates(stmts []ast.Stmt) bool {
	if len(stmts) == 0 {
		return false
	}
	last := stmts[len(stmts)-1]
	switch s := last.(type) {
	case *ast.ReturnStmt:
		return true
	case *ast.BranchStmt:
		return s.Tok == token.BREAK || s.Tok == token.CONTINUE || s.Tok == token.GOTO
	case *ast.ExprStmt:
		return isPanicCall(s)
	case *ast.BlockStmt:
		return alwaysTerminates(s.List)
	case *ast.IfStmt:
		if s.Else == nil {
			return false
		}
		elseBlock, ok := s.Else.(*ast.BlockStmt)
		if ok {
			return alwaysTerminates(s.Body.List) && alwaysTerminates(elseBlock.List)
		}
		if elseIf, ok := s.Else.(*ast.IfStmt); ok {
			return alwaysTerminates(s.Body.List) && alwaysTerminates([]ast.Stmt{elseIf})
		}
	}
	return false
}

func trailingFallthrough(stmts []ast.Stmt) *ast.BranchStmt {
	if len(stmts) == 0 {
		return nil
	}
	if br, ok := stmts[len(stmts)-1].(*ast.BranchStmt); ok && br.Tok == token.FALLTHROUGH {
		return br
	}
	return nil
}

func exprString(n ast.Node) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, token.NewFileSet(), n); err != nil {
		return "?"
	}
	return buf.String()
}

func compactExpr(e ast.Expr) string {
	if e == nil {
		return ""
	}
	return collapseAndTruncate(exprString(e), 72)
}

func compactExprList(list []ast.Expr) string {
	parts := make([]string, 0, len(list))
	for _, e := range list {
		parts = append(parts, exprString(e))
	}
	return collapseAndTruncate(strings.Join(parts, ", "), 72)
}

func compactStmt(s ast.Stmt) string {
	if s == nil {
		return ""
	}
	return collapseAndTruncate(exprString(s), 72)
}

func collapseAndTruncate(s string, maxLen int) string {
	fields := strings.Fields(s)
	out := strings.Join(fields, " ")
	if len(out) > maxLen {
		return out[:maxLen-3] + "..."
	}
	return out
}

func printTextReport(w *os.File, r *RepoReport, topPerPkg int) {
	fmt.Fprintf(w, "Go Statement, Executable Line & AST Branch Coverage Report\n")
	fmt.Fprintf(w, "Module: %s | Mode: %s | Profile: %s\n", r.Module, r.Mode, r.ProfilePath)
	for _, warn := range r.Warnings {
		fmt.Fprintf(w, "WARNING: %s\n", warn)
	}
	fmt.Fprintln(w)
	fmt.Fprintf(w, "%-22s %17s %17s %17s\n",
		"Package", "Statements", "Exec Lines", "AST Branches")
	fmt.Fprintf(w, "%s\n", strings.Repeat("-", 77))

	for _, p := range r.Packages {
		fmt.Fprintf(w, "%-22s %4d/%-4d (%5.1f%%) %4d/%-4d (%5.1f%%) %4d/%-4d (%5.1f%%)\n",
			p.Package,
			p.StmtsCovered, p.StmtsTotal, p.StmtPct,
			p.LinesCovered, p.LinesTotal, p.LinePct,
			p.BranchesCovered, p.BranchesTotal, p.BranchPct,
		)
	}
	fmt.Fprintf(w, "%s\n", strings.Repeat("-", 77))
	fmt.Fprintf(w, "%-22s %4d/%-4d (%5.1f%%) %4d/%-4d (%5.1f%%) %4d/%-4d (%5.1f%%)\n",
		"TOTAL",
		r.StmtsCovered, r.StmtsTotal, r.StmtPct,
		r.LinesCovered, r.LinesTotal, r.LinePct,
		r.BranchesCovered, r.BranchesTotal, r.BranchPct,
	)

	if topPerPkg > 0 {
		fmt.Fprintln(w)
		fmt.Fprintf(w, "Top Uncovered Branches per Package (up to %d each):\n", topPerPkg)
		for _, p := range r.Packages {
			if len(p.Uncovered) == 0 {
				fmt.Fprintf(w, "  %s: (none — 100.0%% branch coverage)\n", p.Package)
				continue
			}
			ranked := prioritizeBranches(p.Uncovered)
			shown := len(ranked)
			if shown > topPerPkg {
				shown = topPerPkg
			}
			fmt.Fprintf(w, "  %s (%d uncovered total, showing top %d):\n", p.Package, len(ranked), shown)
			for _, br := range ranked[:shown] {
				fmt.Fprintf(w, "    - %s:%d [%s] %s (%s)\n",
					br.File, br.Line, br.Kind, br.FuncName, br.Detail)
			}
		}
	}
}

// prioritizeBranches ranks uncovered branches so high-value untested paths
// (explicit else/case/select arms and non-guard logic branches) surface first.
func prioritizeBranches(in []BranchRecord) []BranchRecord {
	out := make([]BranchRecord, len(in))
	copy(out, in)
	priority := func(b BranchRecord) int {
		switch b.Kind {
		case "switch-case", "switch-default", "type-switch-case", "type-switch-default", "select-case", "select-default":
			return 0
		case "if-else", "if-else-if":
			return 1
		case "for-body", "range-body", "for-exit", "range-exit":
			return 2
		case "if-then":
			return 3
		case "switch-implicit-default", "type-switch-implicit-default":
			return 4
		default: // if-implicit-else
			return 5
		}
	}
	sort.Slice(out, func(i, j int) bool {
		pi, pj := priority(out[i]), priority(out[j])
		if pi != pj {
			return pi < pj
		}
		if out[i].File != out[j].File {
			return out[i].File < out[j].File
		}
		if out[i].Line != out[j].Line {
			return out[i].Line < out[j].Line
		}
		return out[i].Kind < out[j].Kind
	})
	return out
}

func escapeMD(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "`", "'")
	return s
}

